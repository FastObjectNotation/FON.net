using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace FON.Generator;


/// <summary>Writes the partial declaration that implements IFonRecord for one record model.</summary>
internal static class RecordEmitter {
    private const string Support = "global::FON.Records.FonRecordSupport";
    private const string Collection = "global::FON.Types.FonCollection";


    public static string Emit(RecordModel model) {
        SourceWriter writer = new SourceWriter();
        writer.Line("// <auto-generated/>");
        writer.Line("#nullable enable annotations");
        writer.Line("#nullable disable warnings");
        writer.Line();

        int opened = 0;
        if (model.Namespace is not null) {
            writer.Open($"namespace {model.Namespace}");
            opened++;
        }
        foreach (TypeDeclarationModel containing in model.Containing) {
            writer.Open($"partial {containing.Keyword} {containing.Name}");
            opened++;
        }

        string recordInterface = $"global::FON.Records.IFonRecord<{model.FullName}>";
        writer.Open($"partial {model.Declaration.Keyword} {model.Declaration.Name} : {recordInterface}");
        EmitToFon(writer, model, recordInterface);
        writer.Line();
        writer.Line();
        EmitFromFon(writer, model, recordInterface);
        writer.Close();

        for (int level = 0; level < opened; level++) {
            writer.Close();
        }
        return writer.ToString();
    }


    private static void EmitToFon(SourceWriter writer, RecordModel model, string recordInterface) {
        writer.Open($"static {Collection} {recordInterface}.ToFon({model.FullName} value)");
        if (!model.IsValueType) {
            writer.Line("global::System.ArgumentNullException.ThrowIfNull(value);");
        }
        writer.Line($"{Collection} collection = new {Collection}();");
        writer.Open("try");
        int index = 0;
        foreach (MemberModel member in model.Written) {
            string local = "member" + index;
            writer.Open($"if (value.{member.Identifier} is {{ }} {local})");
            writer.Line(WriteStatement(member, local));
            writer.Close();
            index++;
        }
        writer.Continue("catch");
        writer.Line("collection.Dispose();");
        writer.Line("throw;");
        writer.Close();
        writer.Line("return collection;");
        writer.Close();
    }


    private static void EmitFromFon(SourceWriter writer, RecordModel model, string recordInterface) {
        writer.Open($"static {model.FullName} {recordInterface}.FromFon({Collection} collection)");
        writer.Line("global::System.ArgumentNullException.ThrowIfNull(collection);");
        MemberModel[] read = model.Read.AsArray();
        if (model.UsesConstructor) {
            writer.Line($"return new {model.FullName}(");
            writer.Indent();
            for (int index = 0; index < read.Length; index++) {
                string separator = index < read.Length - 1 ? "," : string.Empty;
                writer.Line(ReadExpression(read[index]) + separator);
            }
            writer.Outdent();
            writer.Line(");");
        } else {
            writer.Line($"return new {model.FullName}() {{");
            writer.Indent();
            for (int index = 0; index < read.Length; index++) {
                string separator = index < read.Length - 1 ? "," : string.Empty;
                writer.Line($"{read[index].Identifier} = {ReadExpression(read[index])}{separator}");
            }
            writer.Outdent();
            writer.Line("};");
        }
        writer.Close();
    }


    private static string WriteStatement(MemberModel member, string local) {
        string key = Literal(member.Key);
        string type = member.Value.TypeName;
        if (member.Shape == ShapeKind.Array || member.Shape == ShapeKind.List) {
            switch (member.Value.Kind) {
                case ValueKind.Enum:
                    return $"{Support}.WriteEnumList<{type}>(collection, {key}, {local});";
                case ValueKind.Collection:
                    return $"{Support}.WriteCollectionList(collection, {key}, {local});";
                case ValueKind.Record:
                    return $"{Support}.WriteRecordList<{type}>(collection, {key}, {local});";
                default:
                    return $"{Support}.WriteList<{type}>(collection, {key}, {local});";
            }
        }
        switch (member.Value.Kind) {
            case ValueKind.Enum:
                return $"{Support}.WriteEnum<{type}>(collection, {key}, {local});";
            case ValueKind.Collection:
                return $"{Support}.WriteCollection(collection, {key}, {local});";
            case ValueKind.Record:
                return $"{Support}.WriteRecord<{type}>(collection, {key}, {local});";
            default:
                return $"collection.Add({key}, {local});";
        }
    }


    private static string ReadExpression(MemberModel member) {
        string key = Literal(member.Key);
        string type = member.Value.TypeName;
        string optional = member.Optional ? "true" : "false";
        switch (member.Shape) {
            case ShapeKind.Array:
                switch (member.Value.Kind) {
                    case ValueKind.Enum:
                        return $"{Support}.ReadEnumArray<{type}>(collection, {key}, {optional})";
                    case ValueKind.Collection:
                        return $"{Support}.ReadCollectionArray(collection, {key}, {optional})";
                    case ValueKind.Record:
                        return $"{Support}.ReadRecordArray<{type}>(collection, {key}, {optional})";
                    default:
                        return $"{Support}.ReadArray<{type}>(collection, {key}, {optional})";
                }
            case ShapeKind.List:
                switch (member.Value.Kind) {
                    case ValueKind.Enum:
                        return $"{Support}.ReadEnumList<{type}>(collection, {key}, {optional})";
                    case ValueKind.Collection:
                        return $"{Support}.ReadCollectionList(collection, {key}, {optional})";
                    case ValueKind.Record:
                        return $"{Support}.ReadRecordList<{type}>(collection, {key}, {optional})";
                    default:
                        return $"{Support}.ReadList<{type}>(collection, {key}, {optional})";
                }
            case ShapeKind.Nullable:
                switch (member.Value.Kind) {
                    case ValueKind.Enum:
                        return $"{Support}.ReadOptionalEnum<{type}>(collection, {key})";
                    case ValueKind.Record:
                        return $"{Support}.ReadOptionalRecordValue<{type}>(collection, {key})";
                    default:
                        return $"{Support}.ReadOptionalValue<{type}>(collection, {key})";
                }
            default:
                return ReadSingle(member, key, type);
        }
    }


    private static string ReadSingle(MemberModel member, string key, string type) {
        string prefix = member.Optional ? "ReadOptional" : "Read";
        switch (member.Value.Kind) {
            case ValueKind.Number:
                return $"{Support}.ReadValue<{type}>(collection, {key})";
            case ValueKind.String:
                return $"{Support}.{prefix}String(collection, {key})";
            case ValueKind.RawData:
                return $"{Support}.{prefix}RawData(collection, {key})";
            case ValueKind.Collection:
                return $"{Support}.{prefix}Collection(collection, {key})";
            case ValueKind.Enum:
                return $"{Support}.ReadEnum<{type}>(collection, {key})";
            default:
                if (member.Optional && !member.Value.IsValueType) {
                    return $"{Support}.ReadOptionalRecord<{type}>(collection, {key})";
                }
                return $"{Support}.ReadRecord<{type}>(collection, {key})";
        }
    }


    private static string Literal(string text) {
        return SymbolDisplay.FormatLiteral(text, quote: true);
    }



    /// <summary>Builds indented source text with K&amp;R braces.</summary>
    private sealed class SourceWriter {
        private readonly StringBuilder builder = new StringBuilder();
        private int depth;


        public void Line(string text = "") {
            if (text.Length > 0) {
                builder.Append(' ', depth * 4);
                builder.Append(text);
            }
            builder.Append('\n');
        }


        public void Open(string header) {
            Line(header + " {");
            depth++;
        }


        public void Close() {
            depth--;
            Line("}");
        }


        /// <summary>Closes a block and opens the next on the same line, as in <c>} catch {</c>.</summary>
        public void Continue(string header) {
            depth--;
            Line("} " + header + " {");
            depth++;
        }


        public void Indent() {
            depth++;
        }


        public void Outdent() {
            depth--;
        }


        public override string ToString() {
            return builder.ToString();
        }
    }
}
